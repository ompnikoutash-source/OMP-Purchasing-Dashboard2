/* ============================================================
   AD / MB ITEM SALES REVENUE BY MONTH
   DB: DB2/AS400 via ODBC, schema GSFL2K

   Window:
     Past 24 completed calendar months as of 2026-07-31:
       2024-07-01 through 2026-06-30

   Scope:
     Only items whose item number starts with AD or MB.
     One row per item, with one sales-revenue column per month.
   ============================================================ */

SELECT
    TRIM(IM.IMITEM) AS "Item Number",
    TRIM(IM.IMDESC) AS "Description",
    RTRIM(CHAR(IM.IMDIV)) AS "Division",
    TRIM(CHAR(IM.IMVEND)) AS "Vendor Number",
    TRIM(VM.VMNAME) AS "Vendor Name",

    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2024-07-01') AND H.SHIDAT < DATE('2024-08-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2024-07",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2024-08-01') AND H.SHIDAT < DATE('2024-09-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2024-08",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2024-09-01') AND H.SHIDAT < DATE('2024-10-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2024-09",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2024-10-01') AND H.SHIDAT < DATE('2024-11-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2024-10",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2024-11-01') AND H.SHIDAT < DATE('2024-12-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2024-11",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2024-12-01') AND H.SHIDAT < DATE('2025-01-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2024-12",

    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-01-01') AND H.SHIDAT < DATE('2025-02-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-01",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-02-01') AND H.SHIDAT < DATE('2025-03-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-02",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-03-01') AND H.SHIDAT < DATE('2025-04-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-03",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-04-01') AND H.SHIDAT < DATE('2025-05-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-04",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-05-01') AND H.SHIDAT < DATE('2025-06-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-05",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-06-01') AND H.SHIDAT < DATE('2025-07-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-06",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-07-01') AND H.SHIDAT < DATE('2025-08-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-07",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-08-01') AND H.SHIDAT < DATE('2025-09-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-08",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-09-01') AND H.SHIDAT < DATE('2025-10-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-09",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-10-01') AND H.SHIDAT < DATE('2025-11-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-10",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-11-01') AND H.SHIDAT < DATE('2025-12-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-11",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2025-12-01') AND H.SHIDAT < DATE('2026-01-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-12",

    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2026-01-01') AND H.SHIDAT < DATE('2026-02-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-01",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2026-02-01') AND H.SHIDAT < DATE('2026-03-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-02",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2026-03-01') AND H.SHIDAT < DATE('2026-04-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-03",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2026-04-01') AND H.SHIDAT < DATE('2026-05-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-04",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2026-05-01') AND H.SHIDAT < DATE('2026-06-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-05",
    DECIMAL(SUM(CASE WHEN H.SHIDAT >= DATE('2026-06-01') AND H.SHIDAT < DATE('2026-07-01') THEN COALESCE(L.SLENET, 0) ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-06"
FROM GSFL2K.SHHEAD H
JOIN GSFL2K.SHLINE L
  ON L.SLCO = H.SHCO
 AND L.SLLOC = H.SHLOC
 AND L.SLORD# = H.SHORD#
 AND L.SLINV# = H.SHINV#
JOIN GSFL2K.ITEMMAST IM
  ON IM.IMITEM = L.SLITEM
LEFT JOIN GSFL2K.VENDMAST VM
  ON VM.VMVEND = IM.IMVEND
WHERE H.SHIDAT >= DATE('2024-07-01')
  AND H.SHIDAT < DATE('2026-07-01')
  AND (
        TRIM(IM.IMITEM) LIKE 'AD%'
     OR TRIM(IM.IMITEM) LIKE 'MB%'
  )
GROUP BY
    TRIM(IM.IMITEM),
    TRIM(IM.IMDESC),
    RTRIM(CHAR(IM.IMDIV)),
    TRIM(CHAR(IM.IMVEND)),
    TRIM(VM.VMNAME)
ORDER BY
    "Item Number"
