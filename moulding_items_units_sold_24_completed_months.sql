/* ============================================================
   SELECT MOULDING ITEMS - UNITS SOLD BY MONTH
   DB: DB2/AS400 via ODBC, schema GSFL2K

   Window:
     Past 24 completed calendar months as of 2026-07-31:
       2024-07-01 through 2026-06-30

   Scope:
     Same screenshot item list used in the PO purchase history query.

   Screenshot corrections found in ITEMMAST:
     - MCOCAMD120MUL -> MOCAMD120MUL
     - MORIM751      -> MORIMD751
     - MOOQR34PR     -> MOQR34PR

   Unit basis:
     Uses SHLINE.SLBLUO, the billed quantity in the sales/billing UOM.
   ============================================================ */

WITH

ReportItems (ITEM_NUMBER) AS (
    VALUES
        ('MOCAMD120MUL'),
        ('MOBBMD314MUL3'),
        ('MOBBMD314MUL4'),
        ('MOBBMD314MUL5'),
        ('MOBBMD318MUL'),
        ('MOBBMD324MUL'),
        ('MOBBMD329MUL'),
        ('MOBBMD330MUL'),
        ('MOBBMD342MUL'),
        ('MOBBMD387MUL3'),
        ('MOBBMD387MUL4'),
        ('MOBBMD387MUL5'),
        ('MORIMD751'),
        ('MOBSPR300BFJ'),
        ('MOQR34PR')
),

ItemInfo AS (
    SELECT
        TRIM(IM.IMITEM) AS ITEM_NUMBER,
        TRIM(IM.IMDESC) AS DESCRIPTION,
        RTRIM(CHAR(IM.IMDIV)) AS DIVISION,
        TRIM(CHAR(IM.IMVEND)) AS VENDOR_NUMBER
    FROM GSFL2K.ITEMMAST IM
    JOIN ReportItems RI
      ON RI.ITEM_NUMBER = TRIM(IM.IMITEM)
),

SalesLines AS (
    SELECT
        TRIM(L.SLITEM) AS ITEM_NUMBER,
        H.SHIDAT AS INVOICE_DATE,
        COALESCE(L.SLBLUO, 0) AS UNITS_SOLD
    FROM GSFL2K.SHHEAD H
    JOIN GSFL2K.SHLINE L
      ON L.SLCO = H.SHCO
     AND L.SLLOC = H.SHLOC
     AND L.SLORD# = H.SHORD#
     AND L.SLINV# = H.SHINV#
    JOIN ReportItems RI
      ON RI.ITEM_NUMBER = TRIM(L.SLITEM)
    WHERE H.SHIDAT >= DATE('2024-07-01')
      AND H.SHIDAT < DATE('2026-07-01')
)

SELECT
    II.ITEM_NUMBER AS "Item Number",
    II.DESCRIPTION AS "Description",
    II.DIVISION AS "Division",
    II.VENDOR_NUMBER AS "Vendor Number",

    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2024-07-01') AND SL.INVOICE_DATE < DATE('2024-08-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2024-07",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2024-08-01') AND SL.INVOICE_DATE < DATE('2024-09-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2024-08",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2024-09-01') AND SL.INVOICE_DATE < DATE('2024-10-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2024-09",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2024-10-01') AND SL.INVOICE_DATE < DATE('2024-11-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2024-10",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2024-11-01') AND SL.INVOICE_DATE < DATE('2024-12-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2024-11",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2024-12-01') AND SL.INVOICE_DATE < DATE('2025-01-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2024-12",

    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-01-01') AND SL.INVOICE_DATE < DATE('2025-02-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-01",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-02-01') AND SL.INVOICE_DATE < DATE('2025-03-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-02",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-03-01') AND SL.INVOICE_DATE < DATE('2025-04-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-03",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-04-01') AND SL.INVOICE_DATE < DATE('2025-05-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-04",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-05-01') AND SL.INVOICE_DATE < DATE('2025-06-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-05",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-06-01') AND SL.INVOICE_DATE < DATE('2025-07-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-06",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-07-01') AND SL.INVOICE_DATE < DATE('2025-08-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-07",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-08-01') AND SL.INVOICE_DATE < DATE('2025-09-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-08",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-09-01') AND SL.INVOICE_DATE < DATE('2025-10-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-09",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-10-01') AND SL.INVOICE_DATE < DATE('2025-11-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-10",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-11-01') AND SL.INVOICE_DATE < DATE('2025-12-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-11",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-12-01') AND SL.INVOICE_DATE < DATE('2026-01-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-12",

    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-01-01') AND SL.INVOICE_DATE < DATE('2026-02-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-01",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-02-01') AND SL.INVOICE_DATE < DATE('2026-03-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-02",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-03-01') AND SL.INVOICE_DATE < DATE('2026-04-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-03",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-04-01') AND SL.INVOICE_DATE < DATE('2026-05-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-04",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-05-01') AND SL.INVOICE_DATE < DATE('2026-06-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-05",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-06-01') AND SL.INVOICE_DATE < DATE('2026-07-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-06"
FROM ItemInfo II
LEFT JOIN SalesLines SL
  ON SL.ITEM_NUMBER = II.ITEM_NUMBER
GROUP BY
    II.ITEM_NUMBER,
    II.DESCRIPTION,
    II.DIVISION,
    II.VENDOR_NUMBER
ORDER BY
    II.ITEM_NUMBER
