/* ============================================================
   VENDOR 10013 - UNITS SOLD AND SALES REVENUE BY MONTH
   DB: DB2/AS400 via ODBC, schema GSFL2K

   Window:
     Past 15 completed calendar months as of 2026-08-03:
       2025-05-01 through 2026-07-31

   Scope:
     Current ITEMMAST vendor number = 10013.

   Unit basis:
     Uses SHLINE.SLBLUO, the billed quantity in the sales/billing UOM.

   Revenue basis:
     Uses SHLINE.SLENET, the billed line net sales amount.
   ============================================================ */

WITH

VendorItems AS (
    SELECT
        TRIM(IM.IMITEM) AS ITEM_NUMBER,
        TRIM(IM.IMDESC) AS DESCRIPTION,
        IM.IMVEND AS VENDOR_NUMBER,
        TRIM(VM.VMNAME) AS VENDOR_NAME
    FROM GSFL2K.ITEMMAST IM
    LEFT JOIN GSFL2K.VENDMAST VM
      ON VM.VMVEND = IM.IMVEND
    WHERE IM.IMVEND = 10013
),

SalesLines AS (
    SELECT
        TRIM(L.SLITEM) AS ITEM_NUMBER,
        H.SHIDAT AS INVOICE_DATE,
        COALESCE(L.SLBLUO, 0) AS UNITS_SOLD,
        COALESCE(L.SLENET, 0) AS SALES_REVENUE
    FROM GSFL2K.SHHEAD H
    JOIN GSFL2K.SHLINE L
      ON L.SLCO = H.SHCO
     AND L.SLLOC = H.SHLOC
     AND L.SLORD# = H.SHORD#
     AND L.SLINV# = H.SHINV#
    JOIN VendorItems VI
      ON VI.ITEM_NUMBER = TRIM(L.SLITEM)
    WHERE H.SHIDAT >= DATE('2025-05-01')
      AND H.SHIDAT < DATE('2026-08-01')
)

SELECT
    VI.ITEM_NUMBER AS "Item Number",
    VI.DESCRIPTION AS "Description",
    TRIM(CHAR(VI.VENDOR_NUMBER)) AS "Vendor Number",
    VI.VENDOR_NAME AS "Vendor Name",

    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-05-01') AND SL.INVOICE_DATE < DATE('2025-06-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-05",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-06-01') AND SL.INVOICE_DATE < DATE('2025-07-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-06",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-07-01') AND SL.INVOICE_DATE < DATE('2025-08-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-07",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-08-01') AND SL.INVOICE_DATE < DATE('2025-09-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-08",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-09-01') AND SL.INVOICE_DATE < DATE('2025-10-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-09",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-10-01') AND SL.INVOICE_DATE < DATE('2025-11-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-10",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-11-01') AND SL.INVOICE_DATE < DATE('2025-12-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-11",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-12-01') AND SL.INVOICE_DATE < DATE('2026-01-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2025-12",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-01-01') AND SL.INVOICE_DATE < DATE('2026-02-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-01",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-02-01') AND SL.INVOICE_DATE < DATE('2026-03-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-02",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-03-01') AND SL.INVOICE_DATE < DATE('2026-04-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-03",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-04-01') AND SL.INVOICE_DATE < DATE('2026-05-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-04",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-05-01') AND SL.INVOICE_DATE < DATE('2026-06-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-05",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-06-01') AND SL.INVOICE_DATE < DATE('2026-07-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-06",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-07-01') AND SL.INVOICE_DATE < DATE('2026-08-01') THEN SL.UNITS_SOLD ELSE 0 END), 18, 2) AS "Units Sold - 2026-07",

    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-05-01') AND SL.INVOICE_DATE < DATE('2025-06-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-05",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-06-01') AND SL.INVOICE_DATE < DATE('2025-07-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-06",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-07-01') AND SL.INVOICE_DATE < DATE('2025-08-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-07",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-08-01') AND SL.INVOICE_DATE < DATE('2025-09-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-08",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-09-01') AND SL.INVOICE_DATE < DATE('2025-10-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-09",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-10-01') AND SL.INVOICE_DATE < DATE('2025-11-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-10",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-11-01') AND SL.INVOICE_DATE < DATE('2025-12-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-11",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2025-12-01') AND SL.INVOICE_DATE < DATE('2026-01-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2025-12",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-01-01') AND SL.INVOICE_DATE < DATE('2026-02-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-01",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-02-01') AND SL.INVOICE_DATE < DATE('2026-03-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-02",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-03-01') AND SL.INVOICE_DATE < DATE('2026-04-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-03",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-04-01') AND SL.INVOICE_DATE < DATE('2026-05-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-04",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-05-01') AND SL.INVOICE_DATE < DATE('2026-06-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-05",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-06-01') AND SL.INVOICE_DATE < DATE('2026-07-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-06",
    DECIMAL(SUM(CASE WHEN SL.INVOICE_DATE >= DATE('2026-07-01') AND SL.INVOICE_DATE < DATE('2026-08-01') THEN SL.SALES_REVENUE ELSE 0 END), 18, 2) AS "Sales Revenue - 2026-07"
FROM VendorItems VI
LEFT JOIN SalesLines SL
  ON SL.ITEM_NUMBER = VI.ITEM_NUMBER
GROUP BY
    VI.ITEM_NUMBER,
    VI.DESCRIPTION,
    VI.VENDOR_NUMBER,
    VI.VENDOR_NAME
ORDER BY
    VI.ITEM_NUMBER
