    COALESCE(MAX(OO.QTY_OPEN_ORDERS), 0)          AS QTY_OPEN_ORDERS,
    COALESCE(MAX(SH.QTY_INVOICED), 0)             AS QTY_INVOICED,
    SUM(CASE WHEN B.IBLOC NOT IN (17,41,46,90) THEN B.IBQOH - B.IBQOO ELSE 0 END) AS QTY_AVAIL_COMPANYWIDE,
