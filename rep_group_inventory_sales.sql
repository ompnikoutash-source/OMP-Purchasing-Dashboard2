    SELECT
        TRIM(L.OLITEM)      AS ITEM,
        SUM(L.OLBLUO)       AS QTY_OPEN_ORDERS
    FROM GSFL2K.OOLINE L
    JOIN GSFL2K.OOHEAD H
        ON  H.OHORD# = L.OLORD#
        AND H.OHLOC  = L.OLLOC
        AND H.OHCO   = L.OLCO
    WHERE TRIM(H.OHCUST) IN (
        SELECT TRIM(CMCUST)
        FROM GSFL2K.CUSTMAST
        WHERE CMSLMN IN (818, 880, 888)
    )
      AND H.OHOTYP NOT LIKE '%RA%'
      AND H.OHCUST NOT LIKE '%TRANSFER%'
    GROUP BY TRIM(L.OLITEM)
) OO ON OO.ITEM = TRIM(IM.IMITEM)
LEFT JOIN (
    SELECT
        TRIM(L.SLITEM)      AS ITEM,
        SUM(L.SLBLUO)       AS QTY_INVOICED
    FROM GSFL2K.SHLINE L
    JOIN GSFL2K.SHHEAD H
        ON  H.SHCO   = L.SLCO
        AND H.SHLOC  = L.SLLOC
        AND H.SHORD# = L.SLORD#
        AND H.SHINV# = L.SLINV#
    WHERE TRIM(H.SHCUST) IN (
        SELECT TRIM(CMCUST)
        FROM GSFL2K.CUSTMAST
        WHERE CMSLMN IN (818, 880, 888)
    )
    GROUP BY TRIM(L.SLITEM)
